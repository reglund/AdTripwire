/**
 * Output screening for local-model text. The model's words are interpretation: they may
 * not assert compromise or safety, may not name hostnames absent from the evidence, and
 * are always labelled. Screening is sentence-based so a removed claim leaves the rest.
 *
 * Screening is a best-effort filter over normalised text (NFKC, invisible characters and
 * markdown emphasis removed, contractions expanded, soft line wraps joined). It is one of
 * several independent controls; the label, the side-by-side deterministic evidence and
 * the never-stored rule do not depend on it.
 */
import type { AssistContext, GuardrailFlag, ScreenedAssistOutput } from "@adtripwire/shared";
import { sanitizeHostname } from "./context.js";

export const ASSIST_LABEL =
  "Interpretation generated by a local model. It is not evidence and does not change any detection.";

export const OUTPUT_MAX_CHARS = 3000;

// ── Normalisation ────────────────────────────────────────────────────────────────────────
// eslint-disable-next-line no-control-regex -- control characters are exactly what we strip
const CONTROL_RE = /[\u0000-\u0008\u000b\u000c\u000e-\u001f\u007f]/g;
// eslint-disable-next-line no-misleading-character-class, no-irregular-whitespace -- invisible/format characters are exactly what we strip
const INVISIBLE_RE = /[­͏؜ᅟᅠ឴឵᠎​-‏‪-‮⁠-⁤⁪-⁯︀-️﻿ﾠ]/g;
const DOT_LOOKALIKE_RE = /[。．｡․]/g;
// Markdown emphasis markers. Underscores are stripped only at word edges so identifiers such
// as rule ids (known_infra.surveillance_contact) keep their shape and are not mistaken for
// hostnames.
const EMPHASIS_RE =
  /[*~`]+|(?<![\p{L}\p{N}])_+(?=[\p{L}\p{N}])|(?<=[\p{L}\p{N}])_+(?![\p{L}\p{N}])/gu;
const CONTRACTIONS: Array<[RegExp, string]> = [
  [/\b(you|we|they)['’]ve\b/gi, "$1 have"],
  [/\b(you|we|they)['’]re\b/gi, "$1 are"],
  [/\b(it|that|there|he|she|this|what|who)['’]s\b/gi, "$1 is"],
  [/\b(i)['’]m\b/gi, "$1 am"],
  [
    /\b(is|was|are|were|has|have|had|does|do|did|could|would|should|can|must|might|need)n['’]t\b/gi,
    "$1 not",
  ],
  [/\bwon['’]t\b/gi, "will not"],
  [/\bcan['’]t\b/gi, "can not"],
  [/\b(you|we|they|it|he|she)['’]ll\b/gi, "$1 will"],
  [/\b(you|we|they|it|he|she|i)['’]d\b/gi, "$1 would"],
];

/** Normalises model text for both screening and display (plain text only). */
export function normalizeAssistText(raw: string): string {
  let t = raw
    .normalize("NFKC")
    .replace(/\r/g, "")
    .replace(CONTROL_RE, "")
    .replace(INVISIBLE_RE, "");
  t = t.replace(DOT_LOOKALIKE_RE, ".").replace(EMPHASIS_RE, "");
  for (const [re, rep] of CONTRACTIONS) t = t.replace(re, rep);
  // Join soft wraps: a line that does not end a sentence or heading continues on the next
  // line when that line starts in lower case.
  t = t.replace(/([^\n.!?:])\n(?=[a-zæøå])/g, "$1 ");
  return t;
}

// ── Verdict claims ───────────────────────────────────────────────────────────────────────
const SUBJECT =
  "(?:you|your (?:device|phone|iphone|android|computer|laptop|mac|pc|tablet|browser|machine|system|account|data)|the (?:device|phone|iphone|computer|laptop|browser|machine|system|user|account|victim)|this (?:device|phone|computer|laptop|browser|machine|system)|it|they|he|she)";
const BE =
  "(?:is|are|was|were|has been|have been|had been|is being|are being|got|gets|became|appears to be|appear to be|seems to be|seem to be|is likely|are likely|is definitely|is certainly|has definitely been|has certainly been|will be|would be|must be|may well be)";
// Intensifiers only; never a negation, so "is not infected" stays a safety claim.
const ADV =
  "(?:(?:\\w+ly|now|already|still|indeed|almost|very|most|quite|clearly|in fact|without doubt|probably|likely)\\s+){0,2}";
const BAD =
  "(?:infected|compromised|hacked|breached|spied (?:on|upon)|under surveillance|being watched|watched|monitored|tracked by spyware|targeted by spyware|targeted|bugged|exploited|backdoored)";
const GOOD =
  "(?:safe|clean|secure|fine|ok|okay|alright|not infected|not compromised|not affected|not hacked|unaffected|not at risk|free of (?:spyware|malware)|spyware[- ]free|malware[- ]free)";
const SPYWARE =
  "(?:spyware|malware|a trojan|the trojan|surveillance software|stalkerware|pegasus|predator|candiru|devilstongue|hermit|graphite|a backdoor|the backdoor|the exploit|an exploit|the implant|an implant)";

const COMPROMISE_RES: RegExp[] = [
  new RegExp(`\\b${SUBJECT}\\s+${BE}\\s+${ADV}${BAD}\\b`, "i"),
  new RegExp(
    `\\b${SPYWARE}\\s+(?:is|was|has been|had been|got|gets)\\s+${ADV}(?:installed|running|present|active|deployed|executed|delivered|loaded|on (?:your|the|this) (?:device|phone|computer|browser|system))\\b`,
    "i",
  ),
  new RegExp(
    `\\b${SPYWARE}\\s+(?:has|have|had)?\\s*(?:infected|compromised|hacked|breached|exploited|been installed on|installed itself on|taken over)\\b`,
    "i",
  ),
  /\b(?:confirms?|confirmed|proves?|proved|establishes|established)\s+(?:an?\s+|the\s+)?(?:infection|compromise|breach|intrusion|successful attack)\b/i,
  /\b(?:you|your device|the device) (?:has|have) (?:been )?(?:infected|compromised|hacked)\b/i,
  // Norwegian
  /\b(?:du|dere|enheten|telefonen|mobilen|datamaskinen|maskinen|pc-en|nettleseren|systemet|kontoen|den|det)\s+(?:er|ble|var|har blitt|har vært|blir|vil bli|må være)\s+(?:\w+\s+){0,2}(?:infisert|kompromittert|hacket|overvåket|avlyttet|spionert på|angrepet|utsatt for spionvare)\b/i,
  /\b(?:spionvare|skadevare|overvåkingsprogramvare|pegasus|predator)\s+(?:er|ble|har blitt|var)\s+(?:\w+\s+){0,2}(?:installert|aktiv|levert|til stede|kjørende|på enheten)\b/i,
  /\b(?:bekrefter|beviser)\s+(?:en\s+|et\s+)?(?:infeksjon|kompromittering|innbrudd)\b/i,
];
const SAFETY_RES: RegExp[] = [
  new RegExp(`\\b${SUBJECT}\\s+${BE}\\s+${ADV}${GOOD}\\b`, "i"),
  /\b(?:no|there is no|there was no|without any)\s+(?:spyware|malware|infection|compromise|trojan)\s+(?:is|was|has been)?\s*(?:present|found|detected|installed|on (?:your|the) device)\b/i,
  /\bnothing (?:to worry about|harmful happened|bad happened|was installed|malicious happened)\b/i,
  /\b(?:you|your device|the device) (?:has|have) not been (?:infected|compromised|hacked)\b/i,
  // Norwegian
  /\b(?:du|dere|enheten|telefonen|mobilen|datamaskinen|maskinen|nettleseren|systemet|kontoen|den|det)\s+(?:er|var|har vært|ble)\s+(?:\w+\s+){0,2}(?:trygg|trygt|ren|rent|sikker|sikkert|ok|i orden|ikke infisert|ikke kompromittert|ikke berørt|ikke hacket)\b/i,
  /\b(?:ingen|ikke noe)\s+(?:spionvare|skadevare|infeksjon)\s+(?:er|ble|har blitt)?\s*(?:funnet|oppdaget|installert|til stede)\b/i,
  /\bingenting å bekymre seg (?:for|over)\b/i,
];

/**
 * Hedges that must sit DIRECTLY in front of a claim for it to be a caveat we keep ("the
 * evidence cannot show whether the device is infected", "do not assume that you are
 * compromised", "if you fear you are being watched"). Only one optional word may appear
 * between a negation and its verb, so "it is not hard to show that …" or "never lie and
 * they show that …" are not accepted. Hedged claims are kept but flagged.
 */
const NEG =
  "(?:cannot|can not|could not|does not|do not|did not|is not|are not|was not|were not|not|never|unable to|impossible to|no way to|insufficient to|not enough to)";
const EPISTEMIC =
  "(?:show|tell|establish|prove|determine|confirm|mean|know|say|conclude|judge|assess|verify|demonstrate|reveal|imply|indicate|suggest|decide|rule out|assume|presume|infer|treat this as (?:proof|evidence)|take this (?:as|to mean)|read this as|interpret this as)";
const CONNECTOR = "(?:(?:or\\s+)?(?:whether|if|that)\\s+(?:or not\\s+)?)";
const NB_NEG =
  "(?:kan ikke|kunne ikke|viser ikke|betyr ikke|beviser ikke|sier ikke|er ikke mulig å|ikke mulig å|ikke nok til å|ikke)";
const NB_EPISTEMIC =
  "(?:si|fastslå|avgjøre|vise|bevise|bekrefte|vite|konkludere|anta|tolke|lese|ta dette som)";
const NB_CONNECTOR = "(?:(?:eller\\s+)?(?:om|at|hvorvidt)\\s+)";
const HEDGE_DIRECT_RE = new RegExp(
  [
    `\\b${NEG}\\s+(?:\\w+\\s+)?${EPISTEMIC}\\s+${CONNECTOR}?`,
    `\\bnot necessarily\\s+(?:that\\s+)?`,
    `\\bno (?:evidence|proof|indication|sign)s?\\s+(?:that|of|for)\\s+`,
    `\\b(?:regardless of|irrespective of|independent of)\\s+whether\\s+`,
    `\\b(?:if|when|in case|should)\\s+(?:you|they|someone|anyone)\\s+(?:think|believe|fear|suspect|worry|feel|assume|are (?:worried|concerned|afraid))\\s+(?:that\\s+)?`,
    `\\b${NB_NEG}\\s+(?:\\w+\\s+)?${NB_EPISTEMIC}?\\s*${NB_CONNECTOR}`,
    `\\bikke nødvendigvis\\s+(?:at\\s+)?`,
    `\\bingen (?:bevis|indikasjon|tegn)\\s+(?:på|for)\\s+(?:at\\s+)?`,
    `\\bhvis\\s+du\\s+(?:tror|frykter|mistenker|er redd for|er bekymret for|føler)\\s+(?:at\\s+)?`,
    `\\buten\\s+at\\s+`,
  ]
    .map((alt) => `(?:${alt})`)
    .join("|")
    .replace(/^/, "(?:")
    .concat(")$"),
  "i",
);
/**
 * A claim introduced by a connector ("… or that you are compromised") is also kept when a
 * proper hedge phrase appears earlier in the same sentence: "does not prove that spyware
 * executed on your device or that you are compromised".
 */
const HEDGE_EARLIER_RE = new RegExp(
  `\\b${NEG}\\s+(?:\\w+\\s+)?${EPISTEMIC}\\b|\\bnot necessarily\\b|\\bno (?:evidence|proof|indication|sign)s?\\b|\\b${NB_NEG}\\s+(?:\\w+\\s+)?${NB_EPISTEMIC}\\b|\\bingen (?:bevis|indikasjon|tegn)\\b`,
  "i",
);
const CONNECTOR_DIRECT_RE = new RegExp(`(?:${CONNECTOR}|${NB_CONNECTOR})$`, "i");

function isHedged(sentence: string, index: number): boolean {
  const before = sentence.slice(0, index);
  if (HEDGE_DIRECT_RE.test(before.slice(-90))) return true;
  return CONNECTOR_DIRECT_RE.test(before) && HEDGE_EARLIER_RE.test(before);
}

function earliestMatch(sentence: string, res: readonly RegExp[]): number {
  let best = -1;
  for (const re of res) {
    const m = re.exec(sentence);
    if (m && (best === -1 || m.index < best)) best = m.index;
  }
  return best;
}

export type ClaimKind = "compromise" | "safety" | "hedged" | null;

/** Classifies one (normalised) sentence. */
export function claimKind(sentence: string): ClaimKind {
  const s = normalizeAssistText(sentence);
  const c = earliestMatch(s, COMPROMISE_RES);
  if (c >= 0) return isHedged(s, c) ? "hedged" : "compromise";
  const k = earliestMatch(s, SAFETY_RES);
  if (k >= 0) return isHedged(s, k) ? "hedged" : "safety";
  return null;
}

// ── Hostnames, links, misc ───────────────────────────────────────────────────────────────
const INJECTION_RE =
  /\b(?:ignore (?:all |the )?(?:previous|prior|above) instructions|disregard (?:all |the )?(?:previous|prior|above)|system prompt|as an ai language model|new instructions:)\b/i;
const SCHEME_RE = /\b[a-z][a-z0-9+.-]{1,15}:\/\//gi;
const BARE_SLASHES_RE = /(^|[^a-z0-9:])\/\//gi;
const WWW_RE = /\bwww\.[^\s)]+/i;
const HOSTNAME_TOKEN_RE = /\b(?=[a-z0-9-]*[a-z])[a-z0-9-]{1,63}(?:\.[a-z0-9-]{1,63})+\b/gi;
const IPV4_RE = /\b(?:25[0-5]|2[0-4]\d|1?\d?\d)(?:\.(?:25[0-5]|2[0-4]\d|1?\d?\d)){3}\b/g;
const IPV6_RE =
  /\[?(?:(?:[0-9a-f]{1,4}:){2,7}(?:[0-9a-f]{1,4}|:)|::(?:[0-9a-f]{1,4}:){0,6}[0-9a-f]{1,4})\]?/gi;
const SEVERITY_RE = /\b(?:critical|severe|emergency|high[- ]priority|urgent)\b/i;

// Tokens that look like hostnames but are ordinary writing or file names. (Real country
// TLDs such as .md are deliberately NOT here.)
const HOSTNAME_STOP = new Set(["node.js", "e.g.", "i.e.", "vs.", "etc."]);
const HOSTNAME_TLD_STOP = new Set([
  "js",
  "mjs",
  "cjs",
  "ts",
  "txt",
  "json",
  "xml",
  "html",
  "htm",
  "css",
  "png",
  "jpg",
  "jpeg",
  "gif",
  "svg",
  "webp",
  "ico",
  "pdf",
  "woff",
  "woff2",
  "mp4",
  "webm",
  "php",
  "asp",
  "aspx",
]);

function splitSentences(text: string): string[] {
  // Keep lines separate so a removed sentence never eats a heading.
  const out: string[] = [];
  for (const line of text.split(/\n/)) {
    const parts = line.match(/[^.!?]+[.!?]+["')\]]*\s*|[^.!?]+$/g);
    if (parts) out.push(...parts);
    out.push("\n");
  }
  if (out[out.length - 1] === "\n") out.pop();
  return out;
}

const REMOVED_EN =
  "[Statement removed: the model asserted a conclusion about infection or safety that the evidence cannot support.]";
const REMOVED_NB =
  "[Utsagn fjernet: modellen hevdet en konklusjon om infeksjon eller trygghet som bevisene ikke kan støtte.]";
const MASK_EN = "[hostname not in evidence]";
const MASK_NB = "[vertsnavn ikke i bevisene]";
const MASK_IP_EN = "[address not in evidence]";
const MASK_IP_NB = "[adresse ikke i bevisene]";

function allowedHosts(ctx: AssistContext): Set<string> {
  const allowed = new Set<string>();
  for (const h of [...ctx.hostnames, ...ctx.referenceHostnames]) {
    allowed.add(h);
    // Registrable-domain style mentions of allowed hosts ("example.test" for "ads.example.test").
    const labels = h.split(".");
    for (let i = 1; i < labels.length - 1; i++) allowed.add(labels.slice(i).join("."));
  }
  return allowed;
}

/** The hostname at the start of a `/`-chained path that precedes `offset`, if any. */
function pathOwner(whole: string, offset: number): string | null {
  const before = whole.slice(Math.max(0, offset - 400), offset);
  const m = /([a-z0-9][a-z0-9.-]*[a-z0-9])(?:\/[^\s/]*)*\/$/i.exec(before);
  return m ? m[1]!.toLowerCase() : null;
}

export function screenAssistOutput(raw: string, ctx: AssistContext): ScreenedAssistOutput {
  const flags = new Set<GuardrailFlag>();
  let text = normalizeAssistText(raw);
  if (text.length > OUTPUT_MAX_CHARS) {
    text = `${text.slice(0, OUTPUT_MAX_CHARS)}…`;
    flags.add("truncated");
  }
  const nb = ctx.language === "nb";
  const removedText = nb ? REMOVED_NB : REMOVED_EN;
  const mask = nb ? MASK_NB : MASK_EN;
  const maskIp = nb ? MASK_IP_NB : MASK_IP_EN;

  let removed = 0;
  text = splitSentences(text)
    .map((s) => {
      if (s === "\n") return s;
      const claim = claimKind(s);
      if (claim === null) return s;
      if (claim === "hedged") {
        flags.add("hedged_claim");
        return s;
      }
      flags.add(claim === "compromise" ? "asserted_compromise" : "asserted_safety");
      removed++;
      return `${removedText} `;
    })
    .join("");

  if (INJECTION_RE.test(text)) flags.add("instruction_echo");
  if (SCHEME_RE.test(text) || BARE_SLASHES_RE.test(text) || WWW_RE.test(text)) {
    flags.add("contains_url");
    // Strip every scheme and bare "//" so nothing is auto-linkable and the hostname check
    // below sees the bare names.
    text = text.replace(SCHEME_RE, "").replace(BARE_SLASHES_RE, "$1");
  }

  const allowed = allowedHosts(ctx);
  let masked = 0;
  text = text.replace(HOSTNAME_TOKEN_RE, (tok: string, offset: number, whole: string) => {
    const lower = tok.toLowerCase();
    if (HOSTNAME_STOP.has(lower)) return tok;
    const tld = lower.slice(lower.lastIndexOf(".") + 1);
    if (tld.length < 2 || HOSTNAME_TLD_STOP.has(tld)) return tok;
    if (!/^[a-z]+$/.test(tld) && !/^xn--/.test(tld)) return tok;
    const prev = offset > 0 ? whole[offset - 1] : "";
    if (prev === "/" || prev === ".") {
      // A path segment or file name is fine only when the path belongs to an allowed host.
      const owner = pathOwner(whole, offset);
      if (owner && allowed.has(owner)) return tok;
    }
    const norm = sanitizeHostname(lower);
    if (norm && allowed.has(norm)) return tok;
    masked++;
    return mask;
  });
  text = text.replace(IPV4_RE, (tok) => {
    if (allowed.has(tok)) return tok;
    masked++;
    return maskIp;
  });
  text = text.replace(IPV6_RE, (tok) => {
    // Require at least one hex letter or "::" so clock times like 12:30:45 are left alone.
    if (!/[a-f]|::/i.test(tok)) return tok;
    const bare = tok.replace(/^\[|\]$/g, "").toLowerCase();
    if (allowed.has(bare) || allowed.has(`[${bare}]`)) return tok;
    masked++;
    return maskIp;
  });
  if (masked > 0) flags.add("unknown_hostname");

  const high = ctx.detections.some((d) => d.severity === "high_priority");
  if (!high && SEVERITY_RE.test(text)) flags.add("severity_language");

  return {
    text: text
      .replace(/[ \t]+\n/g, "\n")
      .replace(/\n{3,}/g, "\n\n")
      .trim(),
    flags: [...flags],
    removedSentences: removed,
    maskedHostnames: masked,
  };
}
