#!/usr/bin/env node
/**
 * Generates the network-sensor companion feeds from the bundled (non-synthetic) indicator data:
 *
 *   feeds/adtripwire-indicators.stix.json   STIX 2.1 bundle (indicator SDOs)
 *   feeds/adtripwire.zeek-intel.tsv         Zeek Intelligence Framework file
 *   feeds/adtripwire.suricata.rules         Suricata rules (DNS, TLS SNI, HTTP)
 *   feeds/README.md                         formats, caveats, licence
 *
 * Deterministic: the only date used is the indicator sets' `asOf`, so re-running on the same
 * data is byte-identical. Usage: pnpm feeds:export   (or: node scripts/export-feeds.mjs --out DIR)
 */
import { build } from "esbuild";
import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import * as prettier from "prettier";

const root = fileURLToPath(new URL("..", import.meta.url));
const args = process.argv.slice(2);
const outFlag = args.indexOf("--out");
const outDir = outFlag >= 0 && args[outFlag + 1] ? resolve(args[outFlag + 1]) : join(root, "feeds");

const pkg = (name) => join(root, "packages", name, "src", "index.ts");
const bundlePath = join(
  root,
  "node_modules",
  ".cache",
  "adtripwire",
  `export-feeds-${process.pid}.mjs`,
);
await build({
  stdin: {
    contents:
      'export * from "@adtripwire/interop";\nexport { BUNDLED_INDICATOR_SETS } from "@adtripwire/indicators";\n',
    resolveDir: root,
    loader: "ts",
  },
  bundle: true,
  platform: "node",
  format: "esm",
  outfile: bundlePath,
  logLevel: "warning",
  alias: {
    "@adtripwire/interop": pkg("interop"),
    "@adtripwire/shared": pkg("shared"),
    "@adtripwire/indicators": pkg("indicators"),
    "@adtripwire/privacy": pkg("privacy"),
  },
});
const m = await import(pathToFileURL(bundlePath).href);
rmSync(bundlePath, { force: true });

const sets = m.BUNDLED_INDICATOR_SETS.filter((s) => !s.meta.synthetic);
if (sets.length === 0) throw new Error("no non-synthetic indicator sets bundled");
const asOf = sets
  .map((s) => s.meta.asOf)
  .sort()
  .at(-1);
const generatedAt = new Date(`${asOf}T00:00:00.000Z`);

// STIX: one bundle across all sets (objects de-duplicated by id).
const objects = new Map();
for (const set of sets) {
  for (const o of m.indicatorSetToStix(set, { producedAt: generatedAt }).objects) {
    if (!objects.has(o.id)) objects.set(o.id, o);
  }
}
const stix = {
  type: "bundle",
  id: m.stixId("bundle", `feeds:${sets.map((s) => `${s.meta.id}@${s.meta.version}`).join(",")}`),
  objects: [...objects.values()],
};

const prettierConfig = (await prettier.resolveConfig(join(root, "package.json"))) ?? {};
const fmt = (text, parser) => prettier.format(text, { ...prettierConfig, parser });

const selection = m.selectFeedIndicators(sets, generatedAt);
const zeek = m.toZeekIntel(sets, { generatedAt });
const suricata = m.toSuricataRules(sets, { generatedAt });
const stixCount = stix.objects.filter((o) => o.type === "indicator").length;
const zeekCount = zeek.trimEnd().split("\n").length - 1;
const ruleCount = suricata
  .trimEnd()
  .split("\n")
  .filter((l) => l.length > 0).length;

const readme = `# AdTripwire network-sensor feeds

Generated by \`pnpm feeds:export\` (\`scripts/export-feeds.mjs\`) from the bundled indicator
data. Do not edit these files by hand; edit the indicator data and regenerate.

| Set | Version | As of | Indicators |
| --- | --- | --- | --- |
${sets.map((s) => `| \`${s.meta.id}\` | ${s.meta.version} | ${s.meta.asOf} | ${s.indicators.length} |`).join("\n")}

Generated for ${asOf} (the sets' \`asOf\`; no other timestamps are used, so regeneration on the
same data is byte-identical). Included: ${selection.active.length} enabled, unexpired records.
Excluded: ${selection.excluded.expired} expired (\`validTo\` before ${asOf}),
${selection.excluded.disabled} disabled, ${selection.excluded.synthetic} from synthetic test sets.

## Files

- \`adtripwire-indicators.stix.json\` — STIX 2.1 bundle: the AdTripwire \`identity\` and
  ${stixCount} \`indicator\` objects, marked TLP:CLEAR. Expired records are kept here with
  \`valid_until\` so consumers can reason about validity windows.
  - \`hostname\` → \`[domain-name:value = 'host']\` (exact).
  - \`domain\` → \`[domain-name:value = 'apex']\`. STIX patterning has no portable subdomain
    operator for \`domain-name\`, so the pattern names the apex; the description and the
    \`adtripwire:type:domain\` label state that all subdomains are covered.
  - \`hostname_path\` → \`[url:value MATCHES '^https?://host(:[0-9]+)?/path…']\`.
  - Labels: \`adtripwire:<classification>\`, \`adtripwire:type:<type>\`, \`role:<role>\`,
    \`campaign:<campaign>\`. Confidence: high 85, medium 60, low 30.
- \`adtripwire.zeek-intel.tsv\` — Zeek Intelligence Framework file (${zeekCount} entries).
  Load with \`redef Intel::read_files += { ".../adtripwire.zeek-intel.tsv" };\`.
  \`meta.do_notice\` is \`T\` for malicious records only (requires
  \`policy/frameworks/intel/do_notice\`).
- \`adtripwire.suricata.rules\` — Suricata rules (${ruleCount} rules, sids from 9400000,
  4 sids reserved per indicator record, so sids stay stable when records are disabled or
  expire).

## Caveats

- **Exact vs subdomain matching.** Zeek \`Intel::DOMAIN\` matches exact names only: a
  \`domain\` record is emitted as its apex and does NOT cover subdomains. Suricata rules use
  \`dotprefix\` + \`endswith\` for \`domain\` records (apex and subdomains) and
  \`startswith\` + \`endswith\` for \`hostname\` records (exact).
- **Path indicators.** \`hostname_path\` records mark a path on shared infrastructure; the
  host alone is not an indicator. Suricata gets a single HTTP rule (Host + URI prefix), which
  can only fire on cleartext HTTP; there is no DNS or TLS rule for these. Zeek gets an
  \`Intel::URL\` entry, which Zeek compares against the whole host+URI, so only requests to
  exactly that path match.
- **Expired entries excluded.** Time-bounded infrastructure (e.g. rotated CDN staging
  distributions) is dropped from the Zeek and Suricata files when its \`validTo\` is before
  the indicator sets' \`asOf\` (not the time you run the script); regenerate after
  re-curation.
- **Exposure is not compromise.** Ad-delivery and tracking infrastructure is seen by many
  people. A hit means traffic reached documented infrastructure; it does not establish
  targeting, infection or spyware delivery. Surveillance and contextual records use
  \`classtype:policy-violation\`; only malicious records use \`trojan-activity\`.
- Indicator sets describe documented infrastructure as of their published date and are not
  exhaustive. Absence of hits is not evidence that a network or device is clean.

## Licence

Indicator data: CC0 1.0 (via Zero Breach; facts from the cited reports). The generated files
in this directory are also released under CC0 1.0.
`;

mkdirSync(outDir, { recursive: true });
writeFileSync(
  join(outDir, "adtripwire-indicators.stix.json"),
  await fmt(JSON.stringify(stix), "json"),
);
writeFileSync(join(outDir, "adtripwire.zeek-intel.tsv"), zeek);
writeFileSync(join(outDir, "adtripwire.suricata.rules"), suricata);
writeFileSync(join(outDir, "README.md"), await fmt(readme, "markdown"));
console.log(
  `feeds: ${stixCount} STIX indicators, ${zeekCount} Zeek entries, ${ruleCount} Suricata rules → ${outDir}`,
);
