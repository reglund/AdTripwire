/**
 * Generates docs/detection-methodology.md's rule catalogue from the rule definitions, so the
 * documentation cannot drift from the code. Run: pnpm docs:rules
 */
import { writeFileSync, readFileSync } from "node:fs";
import { ALL_RULES, JS_MARKER_DESCRIPTIONS } from "@adtripwire/detection-engine";

const CATEGORY_TITLES: Record<string, string> = {
  known_infrastructure: "A — Known infrastructure",
  ad_delivery_behaviour: "B — Suspicious ad-delivery behaviour",
  profiling: "C — Fingerprinting and invasive profiling",
  javascript_technique: "D — Suspicious JavaScript techniques",
  temporal_correlation: "E — Temporal correlation",
  repeated_exposure: "F — Repeated exposure",
};

const lines: string[] = [];
lines.push(
  "<!-- GENERATED by scripts/dump-rules.ts from the rule definitions. Edit the rules, not this section. -->",
);
lines.push("");
lines.push(`Rule count: ${ALL_RULES.length}.`);
lines.push("");
for (const [cat, title] of Object.entries(CATEGORY_TITLES)) {
  const rules = ALL_RULES.filter((r) => r.definition.category === cat);
  if (rules.length === 0) continue;
  lines.push(`### ${title}`);
  lines.push("");
  for (const r of rules) {
    const d = r.definition;
    lines.push(`#### \`${d.id}\` — ${d.name} (v${d.version})`);
    lines.push("");
    lines.push(d.description);
    lines.push("");
    lines.push(`- **Default severity:** ${d.severity} · **Confidence:** ${d.confidence}`);
    lines.push(`- **Confidence basis:** ${d.confidenceBasis}`);
    lines.push(`- **Required evidence:** ${d.requiredEvidence.join("; ")}`);
    lines.push(
      `- **Required capabilities:** ${d.requiredCapabilities.length ? d.requiredCapabilities.map((c) => `\`${c}\``).join(", ") : "none"}${(r as { anyOfCapabilities?: string[] }).anyOfCapabilities?.length ? ` · **any of:** ${(r as { anyOfCapabilities?: string[] }).anyOfCapabilities!.map((c) => `\`${c}\``).join(", ")}` : ""}`,
    );
    lines.push(`- **Limitations:** ${d.limitations.join(" ")}`);
    lines.push(`- **False-positive considerations:** ${d.falsePositiveConsiderations.join(" ")}`);
    lines.push(`- **References:** ${d.references.map((x) => `[${x.title}](${x.url})`).join(", ")}`);
    lines.push("");
  }
}
lines.push("### JavaScript markers");
lines.push("");
lines.push(
  "Marker identifiers produced by the response analyser (only identifiers are stored, never source text):",
);
lines.push("");
lines.push("| Marker | Meaning |");
lines.push("|---|---|");
for (const [k, v] of Object.entries(JS_MARKER_DESCRIPTIONS).sort())
  lines.push(`| \`${k}\` | ${v} |`);
lines.push("");

const target = "docs/detection-methodology.md";
const START = "<!-- RULES:START -->";
const END = "<!-- RULES:END -->";
let doc = readFileSync(target, "utf8");
const a = doc.indexOf(START);
const b = doc.indexOf(END);
if (a < 0 || b < 0) throw new Error(`markers ${START}/${END} missing in ${target}`);
doc = doc.slice(0, a + START.length) + "\n" + lines.join("\n") + "\n" + doc.slice(b);
writeFileSync(target, doc);
console.log(`updated ${target} with ${ALL_RULES.length} rules`);
